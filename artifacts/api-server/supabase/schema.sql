create table if not exists public.buildings (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  name text not null,
  short_name text not null,
  category text not null check (category in ('academic', 'admin', 'facility', 'sports')),
  description text not null default '',
  floors integer not null default 1 check (floors > 0),
  floors_locations text[] not null default array['Ground']::text[],
  rooms text[] not null default array[]::text[],
  latitude double precision not null default 0,
  longitude double precision not null default 0,
  color text not null default '#800000',
  images text[] not null default array[]::text[],
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.users (
  email text primary key,
  username text not null,
  name text not null,
  picture text,
  last_login_at timestamptz not null default now()
);

create table if not exists public.admin_settings (
  id smallint primary key default 1 check (id = 1),
  email text not null,
  name text not null,
  password_hash text not null,
  password_salt text not null
);

alter table public.buildings enable row level security;
alter table public.users enable row level security;
alter table public.admin_settings enable row level security;

grant all on table public.buildings, public.users, public.admin_settings to service_role;
grant usage, select on all sequences in schema public to service_role;

