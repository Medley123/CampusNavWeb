create or replace function public.sync_building_id_sequence()
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  max_id bigint;
begin
  select coalesce(max(id), 0) into max_id from public.buildings;
  perform setval(
    pg_get_serial_sequence('public.buildings', 'id')::regclass,
    greatest(max_id, 1),
    max_id > 0
  );
end;
$$;

revoke all on function public.sync_building_id_sequence() from public, anon, authenticated;
grant execute on function public.sync_building_id_sequence() to service_role;