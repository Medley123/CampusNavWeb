create table if not exists public.buildings (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  name text not null,
  short_name text not null,
  category text not null check (category in ('academic', 'admin', 'facility', 'sports')),
  description text not null default '',
  floors integer not null default 1 check (floors > 0),
  floors_locations text[] not null default array['Ground']::text[],
  rooms text[] not null default array[]::text[],
  latitude double precision not null default 0,
  longitude double precision not null default 0,
  color text not null default '#800000',
  images text[] not null default array[]::text[],
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.buildings
  add column if not exists campus_name text not null default 'CTU Danao Campus';

create table if not exists public.users (
  email text primary key,
  username text not null,
  name text not null,
  picture text,
  last_login_at timestamptz not null default now(),
  password_hash text,
  password_salt text,
  password_reset_code_hash text,
  password_reset_expires_at timestamptz
);

alter table public.users
  add column if not exists password_hash text,
  add column if not exists password_salt text,
  add column if not exists password_reset_code_hash text,
  add column if not exists password_reset_expires_at timestamptz;

create unique index if not exists users_username_unique_idx on public.users (lower(username));

create table if not exists public.admin_settings (
  id smallint primary key default 1 check (id = 1),
  email text not null,
  name text not null,
  password_hash text not null,
  password_salt text not null
);

create table if not exists public.admin_accounts (
  id bigint generated by default as identity primary key,
  email text not null unique,
  name text not null,
  password_hash text not null,
  password_salt text not null,
  role text not null check (role in ('super_admin', 'campus_admin')),
  campus_name text,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  check ((role = 'super_admin' and campus_name is null) or (role = 'campus_admin' and campus_name is not null))
);

create table if not exists public.campus_floor_plans (
  id bigint generated by default as identity primary key,
  campus_name text not null,
  floor_level text not null check (floor_level in ('Ground', '2F', '3F', '4F')),
  image_url text not null,
  north double precision not null,
  south double precision not null,
  east double precision not null,
  west double precision not null,
  updated_at timestamptz not null default now(),
  unique (campus_name, floor_level),
  check (north > south and east > west),
  check (north <= 85 and south >= -85 and east <= 180 and west >= -180)
);

create table if not exists public.floor_legend_colors (
  floor_level text primary key check (floor_level in ('Ground', '2F', '3F', '4F')),
  color text not null check (color ~ '^#[0-9A-Fa-f]{6}$'),
  updated_at timestamptz not null default now()
);

